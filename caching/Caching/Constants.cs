using System;

namespace FiftyOne.Caching
{
    /// <summary>
    /// The default values the cache builders use when no method sets one.
    /// </summary>
    [System.Diagnostics.CodeAnalysis.SuppressMessage("Naming",
        "CA1707:Identifiers should not contain underscores",
        Justification = "51Degrees coding style is for constant names " +
            "to be all-caps with an underscore to separate words.")]
    public static class Constants
    {
        /// <summary>
        /// Whether a put cache replaces the value of a key it already
        /// holds, when the builder is not told.
        /// </summary>
        public const bool LRU_PUT_CACHE_DEFAULT_UPDATE_EXISTING = false;

        /// <summary>
        /// The number of concurrent requests an LRU cache expects when the
        /// builder is not told, which is the number of processors the
        /// machine has. The cache keeps one linked list for each.
        /// </summary>
        public static int LRU_CACHE_DEFAULT_CONCURRENCY =>
            Environment.ProcessorCount;
    }
}
